using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Xml.Linq;

namespace _BOA_
{
    partial class BoaManager
    {
        internal static IEnumerable<string> EnumerateScriptFiles(string directory)
        {
            foreach (string file in Directory.EnumerateFiles(directory, "*.cs"))
                yield return file;

            foreach (string child in Directory.EnumerateDirectories(directory))
            {
                string name = Path.GetFileName(child);
                if (name.Equals("bin", StringComparison.OrdinalIgnoreCase) || name.Equals("obj", StringComparison.OrdinalIgnoreCase))
                    continue;
                foreach (string file in EnumerateScriptFiles(child))
                    yield return file;
            }
        }

        //----------------------------------------------------------------------------------------------------------

        static void WriteScriptsProject(DirectoryInfo directory, CSharpCompilation compilation)
        {
            var parseOptions = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions ?? CSharpParseOptions.Default;
            var paths = compilation.References.OfType<PortableExecutableReference>().Select(reference => reference.FilePath).Where(path => !string.IsNullOrEmpty(path)).Distinct(StringComparer.Ordinal).OrderBy(path => path, StringComparer.Ordinal);
            var project = new XDocument(
                new XComment("Generated by BOA for external editor language services. The game compiles and loads the scripts."),
                new XElement("Project",
                    new XElement("PropertyGroup",
                        new XElement("BaseIntermediateOutputPath", "$(MSBuildProjectDirectory)/../temp/boa-ide/obj/"),
                        new XElement("BaseOutputPath", "$(MSBuildProjectDirectory)/../temp/boa-ide/bin/")),
                    new XElement("Import", new XAttribute("Project", "Sdk.props"), new XAttribute("Sdk", "Microsoft.NET.Sdk")),
                    new XElement("PropertyGroup",
                        new XElement("TargetFramework", "netstandard2.1"),
                        new XElement("OutputType", "Library"),
                        new XElement("AssemblyName", "BOA.Scripts"),
                        new XElement("LangVersion", LanguageVersionFacts.ToDisplayString(parseOptions.LanguageVersion)),
                        new XElement("Nullable", "disable"),
                        new XElement("ImplicitUsings", "disable"),
                        new XElement("DisableImplicitFrameworkDefines", "true"),
                        new XElement("EnableDefaultItems", "false"),
                        new XElement("GenerateAssemblyInfo", "false"),
                        new XElement("GenerateTargetFrameworkAttribute", "false"),
                        new XElement("EnableNETAnalyzers", "false"),
                        new XElement("NoStdLib", "true"),
                        new XElement("DisableImplicitFrameworkReferences", "true")),
                    new XElement("ItemGroup", new XElement("Compile", new XAttribute("Include", "**/*.cs"), new XAttribute("Exclude", "**/bin/**;**/obj/**"))),
                    new XElement("ItemGroup", paths.Select(path => new XElement("Reference", new XAttribute("Include", EscapeProjectPath(Path.GetFileNameWithoutExtension(path))),
                        new XElement("HintPath", EscapeProjectPath(Path.GetRelativePath(directory.FullName, path))),
                        new XElement("Private", "false")))),
                    new XElement("Import", new XAttribute("Project", "Sdk.targets"), new XAttribute("Sdk", "Microsoft.NET.Sdk")),
                    new XElement("PropertyGroup", new XElement("DefineConstants", string.Join(";", parseOptions.PreprocessorSymbolNames)))));

            string projectPath = Path.Combine(directory.FullName, "BOA.Scripts.csproj");
            string text = project.ToString() + Environment.NewLine;
            if (!File.Exists(projectPath) || File.ReadAllText(projectPath) != text)
                File.WriteAllText(projectPath, text);
        }

        static string EscapeProjectPath(string path) => string.Concat(path.Select(character => "%$@();?*".Contains(character) ? "%" + ((int)character).ToString("X2") : character.ToString()));
    }
}
